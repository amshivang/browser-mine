import { test, expect } from '@playwright/test';

test('new expedition renders, movement works, inventory crafts, and saves survive reload', async ({ page }) => {
  const errors: string[] = [];
  await page.addInitScript(() => { if (!localStorage.getItem('browser-mine-settings')) localStorage.setItem('browser-mine-settings', JSON.stringify({ shadows: false, renderDistance: 2, loadingDistance: 2, graphics: 'low' })); });
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/?qa');
  await expect(page.getByRole('button', { name: 'Create New World' })).toBeVisible();
  await page.getByRole('button', { name: 'Create New World' }).click();
  await page.locator('#world-name').fill('Verification Wild');
  await page.locator('#world-seed').fill('sunward-2026');
  await page.getByRole('button', { name: 'Create & explore' }).click();
  await expect(page.locator('.hud')).toBeVisible({ timeout: 60000 });
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'test-results/expedition.png' });
  await page.locator('.game-canvas').click({ position: { x: 650, y: 390 } });
  await page.waitForFunction(() => !!document.pointerLockElement);
  await page.evaluate(() => { const g = (window as any).__game; const y = g.world.generator.heightAt(8, 8); for (let x = 7; x <= 9; x++) for (let z = 3; z <= 9; z++) { g.world.setBlock(x, y, z, 3); for (let dy = 1; dy <= 4; dy++) g.world.setBlock(x, y + dy, z, 0); } g.player.setPosition(8.5, y + 1, 8.5); g.player.velocity.set(0, 0, 0); g.player.yaw = 0; });
  const before = await page.evaluate(() => (window as any).__game.player.object.position.toArray());
  await page.keyboard.down('KeyW'); await page.waitForTimeout(2200); await page.keyboard.up('KeyW');
  const after = await page.evaluate(() => (window as any).__game.player.object.position.toArray());
  expect(Math.hypot(after[0] - before[0], after[2] - before[2])).toBeGreaterThan(1);
  await page.evaluate(() => { const g = (window as any).__game; g.player.setPosition(8.5, g.world.generator.heightAt(8, 8) + 1, 8.5); g.player.velocity.set(0, 0, 0); });
  await page.waitForFunction(() => (window as any).__game.player.grounded);
  await page.keyboard.down('Space');
  await expect.poll(() => page.evaluate(() => (window as any).__game.player.object.position.y), { timeout: 10000 }).toBeGreaterThan(await page.evaluate(() => (window as any).__game.world.generator.heightAt(8, 8) + 1.1));
  await page.keyboard.up('Space');
  await page.waitForTimeout(700);
  await page.keyboard.press('KeyE');
  await expect(page.getByRole('heading', { name: 'Field pack' })).toBeVisible();
  await page.locator('[data-recipe="planks"]').click();
  expect(await page.evaluate(() => (window as any).__game.player.inventory.count('plank'))).toBe(4);
  await page.locator('.inventory-grid .slot[data-slot="4"]').dragTo(page.locator('.inventory-grid .slot[data-slot="8"]'));
  expect(await page.evaluate(() => (window as any).__game.player.inventory.slots[8]?.id)).toBe('plank');
  await page.keyboard.press('KeyE');
  await page.keyboard.press('F5'); await page.waitForTimeout(700);
  const saved = await page.evaluate(async () => { const g = (window as any).__game; return await g.saves.load(g.worldInfo.id); });
  expect(saved.player.inventory[8].id).toBe('plank');
  await page.reload();
  await page.getByRole('button', { name: 'Load World' }).click();
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await expect(page.locator('.hud')).toBeVisible({ timeout: 60000 });
  const restored = await page.evaluate(() => { const g = (window as any).__game; return { inventory: g.player.inventory.serialize(), pos: g.player.object.position.toArray() }; });
  expect(restored.inventory[8].id).toBe('plank');
  expect(Math.abs(restored.pos[0] - saved.player.position[0])).toBeLessThan(.1);
  expect(errors).toEqual([]);
});
